/** Materialize reading pages so VitePress 1.6's filesystem-based search indexes them. */
import { mkdirSync, readdirSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs'
import path from 'node:path'
import { repoRoot, readingRoutes } from './book-sources.mjs'

const directory = path.join(repoRoot, 'docs', 'book')
const marker = '<!-- Generated by prepare-book.mjs; edit bms-book/book/ or BMS书籍清单.md. -->'
const glossaryMarker = '<!-- Generated by prepare-book.mjs from book/glossary.md. -->'
mkdirSync(directory, { recursive: true })
const routes = readingRoutes()
const names = new Set(routes.map((route) => `${route.params.chapter}.md`))
for (const name of readdirSync(directory)) {
  const file = path.resolve(directory, name)
  if (path.dirname(file) !== directory) throw new Error(`无效书稿路径：${file}`)
  if (name.endsWith('.md') && !names.has(name) && readFileSync(file, 'utf8').includes(marker)) {
    unlinkSync(file)
  }
}
for (const route of routes) {
  const file = path.resolve(directory, `${route.params.chapter}.md`)
  if (path.dirname(file) !== directory) throw new Error(`无效章节名：${route.params.chapter}`)
  const content = `${route.content}\n${marker}\n`
  for (const image of content.matchAll(/<img\b[^>]*>/g)) {
    const attributes = [...image[0].matchAll(/\s([:\w-]+)=/g)].map((match) => match[1])
    const duplicate = attributes.find((name, index) => attributes.indexOf(name) !== index)
    if (duplicate) {
      throw new Error(`生成章节含重复图片属性：${route.params.chapter} · ${duplicate} · ${image[0]}`)
    }
  }
  writeFileSync(file, content)
}

const glossarySource = readFileSync(path.join(repoRoot, 'book', 'glossary.md'), 'utf8')
const [glossaryTitle, ...glossaryBody] = glossarySource.replace(/\r\n/g, '\n').split('\n')
if (!glossaryTitle.startsWith('# ')) throw new Error('book/glossary.md 缺少一级标题')
writeFileSync(path.join(repoRoot, 'docs', 'glossary-merged.md'), `---
description: 卷一与卷二合并的术语表：术语、英文、定义、所属卷与相关条目。
editLink: false
---

${glossaryTitle}

> 站点速查表见 [BMS 术语表](./glossary.md)；本页按书稿生成，与两卷印刷版附录同源。

${glossaryBody.join('\n').trim()}

${glossaryMarker}
`)
console.log(`prepared: ${routes.length} reading pages from book manuscripts and reading list`)
