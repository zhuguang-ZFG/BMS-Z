class Pen:
    def __init__(self):
        self.parts = []
        self.serial = 0

    def seed(self):
        self.serial += 1
        return f"reading-{self.serial}"

    def path(self, points, color=INK, width=3, dash=None):
        self.parts.append(line(points, self.seed(), color, width, dash))

    def rect(self, x, y, w, h, fill="none", color=INK):
        self.parts.append(rough_rect(x, y, w, h, self.seed(), fill, color, 2.7))

    def circle(self, x, y, r, fill="none", color=INK):
        self.parts.append(rough_circle(x, y, r, self.seed(), fill, color, 2.7))

    def text(self, x, y, value, size=26, anchor="middle", color=INK):
        self.parts.append(
            f'<text x="{x}" y="{y}" font-size="{size}" '
            f'text-anchor="{anchor}" fill="{color}">{html.escape(value)}</text>'
        )

    def arrow(self, x1, y1, x2, y2, color=INK, dash=None):
        self.path([(x1, y1), (x2, y2)], color, 3, dash)
        a = math.atan2(y2 - y1, x2 - x1)
        self.path(
            [
                (x2 - 12 * math.cos(a - 0.5), y2 - 12 * math.sin(a - 0.5)),
                (x2, y2),
                (x2 - 12 * math.cos(a + 0.5), y2 - 12 * math.sin(a + 0.5)),
            ],
            color,
        )

    def hatch(self, x, y, w, h):
        for d in range(0, int(w), 17):
            self.path([(x + d, y + h), (x + min(d + 14, w), y)], width=1)

    def cell(self, x, y, level=0.5, w=110, h=170):
        self.rect(x + w * 0.35, y - 12, w * 0.3, 12, PAPER)
        self.rect(x, y, w, h, PAPER)
        water = y + h * (1 - level)
        self.rect(x + 7, water, w - 14, y + h - water - 7, WASH)
        self.path([(x + 8, water), (x + w * 0.45, water - 2), (x + w - 8, water + 1)])
        self.hatch(x + 15, y + h - 27, w - 30, 15)

    def meter(self, x, y, value):
        self.rect(x - 85, y - 62, 170, 124, PAPER)
        self.rect(x - 69, y - 43, 138, 52, WASH)
        self.text(x, y - 8, value, 27)
        self.circle(x, y + 37, 13)
        self.path([(x, y + 37), (x + 7, y + 27)])

    def sheet(self, x, y, w=180, h=190):
        self.rect(x, y, w, h, PAPER)
        self.path([(x + w - 28, y), (x + w - 28, y + 28), (x + w, y + 28)])
        # Keep handwriting clear of the paper's ruled lines.
        for i in range(2):
            self.path(
                [(x + 20, y + h - 34 + i * 17), (x + w - 25, y + h - 34 + i * 17)],
                width=1.0,
            )

    def axes(self, x, y, w, h):
        self.arrow(x, y, x + w, y)
        self.arrow(x, y, x, y - h)

    def wave(self, x, y, w, h, kind="rise", color=INK, dash=None, rate=4):
        points = []
        for i in range(41):
            t = i / 40
            v = (1 - math.exp(-rate * t)) if kind == "rise" else math.exp(-rate * t)
            points.append((x + t * w, y - v * h))
        self.path(points, color, 3, dash)


