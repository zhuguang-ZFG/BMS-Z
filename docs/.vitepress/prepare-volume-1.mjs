function copyAssets(files) {
  rmSync(generatedAssetsDir, { recursive: true, force: true })
  mkdirSync(generatedAssetsDir, { recursive: true })
  const copied = new Set()
  for (const relative of files) {
    if (relative.split('/').includes('..')) throw new Error(`非法资源路径：${relative}`)
    const source = relative === 'static/roadmap.svg'
      ? path.join(repoRoot, 'analog', 'analog-book', 'static', 'roadmap.svg')
      : path.join(volumeOneAssets, relative)
    if (!existsSync(source)) throw new Error(`资源不存在：assets/${relative}`)
    const destination = path.join(generatedAssetsDir, relative)
    mkdirSync(path.dirname(destination), { recursive: true })
    copyFileSync(source, destination)
    copied.add(relative)
    if (relative.startsWith('svg/') && relative.endsWith('.svg')) {
      const still = `${relative.slice(0, -4)}.reduce.svg`
      const svg = readFileSync(source, 'utf8')
      const reduced = svg.includes(reduceCss.trim())
        ? svg
        : svg.replace(/<\/svg>\s*$/, `${reduceCss}</svg>`)
      writeFileSync(path.join(generatedAssetsDir, still), reduced)
      copied.add(still)
    }
  }
  return copied
}

function collectAssets(content) {
  const files = new Set(['static/roadmap.svg'])
  for (const match of content.matchAll(/(?:src|href)="(?:\.\.)?\/volume-1-assets\/([^"#?]+)"/g)) {
    files.add(decodeURIComponent(match[1]))
  }
  for (const match of content.matchAll(/\]\(\.\.\/volume-1-assets\/([^)#?]+)\)/g)) {
    files.add(decodeURIComponent(match[1]))
  }
  return [...files].sort()
}

function cleanGenerated() {
  mkdirSync(generatedDir, { recursive: true })
  for (const name of readdirSync(generatedDir)) {
    const file = path.join(generatedDir, name)
    if (name.endsWith('.md') && readFileSync(file, 'utf8').includes(marker)) unlinkSync(file)
  }
}

export function prepareVolumeOne() {
  cleanGenerated()
  const outputs = new Map()
  for (const page of volumeOne.pages) {
    if (page.file === galleryPage.file) continue
    outputs.set(page.file, buildPageContent(page))
  }
  const gallery = buildGalleryContent(animationIndex())
  outputs.set(galleryPage.file, gallery)
  outputs.set(landingPage.file, buildLandingContent())

  for (const [file, content] of outputs) writeFileSync(path.join(generatedDir, file), content)

  const calc = buildCalcModule()
  mkdirSync(path.dirname(generatedCalcFile), { recursive: true })
  writeFileSync(generatedCalcFile, calc)

  const assets = collectAssets([...outputs.values()].join('\n'))
  const copied = copyAssets(assets)
  console.log(`prepared: ${volumeOne.pages.length} volume-I pages, gallery (${animationIndex().length} cards), `
    + `${copied.size} assets from ${volumeOneManifestPath}`)
  return { pages: outputs.size, assets: copied.size }
}

