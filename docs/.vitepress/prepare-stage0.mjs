import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../stages')
const source = readFileSync(path.join(directory, 'stage-0-前置知识.md'), 'utf8').replace(/\r\n/g, '\n')
const marker = '<!-- Generated by prepare-stage0.mjs; edit stage-0-前置知识.md. -->'

function at(heading) {
  const match = `\n${heading}\n`
  const index = source.indexOf(match)
  if (index < 0 || source.indexOf(match, index + match.length) >= 0) {
    throw new Error(`阶段 0 拆分标题缺失或重复：${heading}`)
  }
  return index + 1
}

function section(start, end) {
  const from = at(start)
  const to = end ? at(end) : source.length
  if (from >= to) throw new Error(`阶段 0 拆分顺序错误：${start}`)
  return source.slice(from, to).trim()
}

