function uniqueIndex(source, token) {
  const match = `\n${token}`
  const index = source.indexOf(match)
  if (index < 0 || source.indexOf(match, index + match.length) >= 0) {
    throw new Error(`阶段 4 拆分边界缺失或重复：${token}`)
  }
  return index + 1
}

export function extractSegment(source, [start, end]) {
  const from = uniqueIndex(source, start)
  const to = uniqueIndex(source, end)
  if (from >= to) throw new Error(`阶段 4 拆分顺序错误：${start}`)
  return source.slice(from, to).trim()
}

