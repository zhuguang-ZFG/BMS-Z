  afe: '## 3.2 AFE 精读：以 BQ769x0/x2 为线 [分析]',
  daisy: '## 3.3 高压采样与隔离菊花链 [分析]',
  firmware: '## 3.4 固件分层与状态机 [应用]',
  switch: '## 3.5 高边与低边功率开关 [评价]',
  pcb: '## 3.6 原理图与 PCB：五条纪律 [应用]',
