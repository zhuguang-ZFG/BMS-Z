export function buildStage6Pages(source) {
  const normalized = source.replace(/\r\n/g, '\n')
  return pageSpecs.map((page) => {
    const body = page.segments
      .map((name) => extractSegment(normalized, readingSegments[name]))
      .join('\n\n')
    const frontmatter = `---\ndescription: ${page.description}\neditLink: false\nnext: false\n---`
    const optional =
      '[选读：EMC、并簇与热管理](./stage-6-选读-系统边界.md) · ' +
      '[选读：故障回放与云端](./stage-6-选读-固件与云端.md) · ' +
      '[选读：算法、法规与自测](./stage-6-选读-算法法规与自测.md)'
    const navigation = `${page.next} · [完整讲义与原有锚点](./${sourceFile})\n\n${optional}`
    const content = `${frontmatter}\n\n# ${page.title}\n\n${page.intro}\n\n> **阅读边界**　这是一条短路径，不删公式、阈值和适用条件；需要旁支时再打开文末选读。\n\n${body}\n\n---\n\n${navigation}\n\n${marker}\n`
    return { ...page, content }
  })
}

function writePages() {
  const source = readFileSync(path.join(directory, sourceFile), 'utf8')
  const pages = buildStage6Pages(source)
  for (const page of pages) writeFileSync(path.join(directory, page.file), page.content)
  console.log(`prepared: ${pages.length} Stage 6 reading pages from full lecture`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) writePages()
