"""生成 gates_report.txt；不要手改输出文件。"""
from __future__ import annotations

from frame_gate import FrameGate, build_frame


def build_stream() -> bytes:
    good = build_frame(0x20, 0x03, b"ok")
    bad = bytearray(build_frame(0x21, 0x01, b"no"))
    bad[-1] ^= 0xFF
    return good + bytes(bad)


def main() -> None:
    gate = FrameGate()
    gate.feed(build_stream())
    print("# generated by make_report.py; do not edit")
    print(f"frames={len(gate.frames)} bad_crc={gate.bad_crc} bad_len={gate.bad_len}")


if __name__ == "__main__":
    main()
