def tolerance_three():
    return two_col(
        '三个 ±1%：WC 3%，3σ 也是 3%',
        '±1% 是均匀分布半宽 a，σ=a/√3=0.577%；三项独立。',
        {
            'head': 'WC 最坏情况',
            'items': [
                ('三项同向取极限', ('1%+1%+1% = 3%', '回答最坏会不会超规')),
                ('用途', ('给定容差域内的界限', '按风险与适用标准验收')),
                ('概率', ('只给界限，不给概率', '实际概率须另建分布')),
                ('用途', ('安全边界', '不可返修场合')),
            ],
            'note': '先问“最坏会不会坏”。',
        },
        {
            'head': 'RSS 均方根',
            'items': [
                ('单项 σ', ('1%/√3 = 0.577%', '极限不是 σ')),
                ('三项 σ_total', ('√3 × 0.577% = 1.0%', '独立随机')),
                ('3σ', ('3.0%', '覆盖率还取决于分布')),
                ('用途', ('统计尺度与贡献分析', '不能直接保证良率')),
            ],
            'note': '再问“大多数落在哪”。',
        },
        'WC 与 3σ 都等于 3%；把 ±1% 当 1σ 会多算成 5.2%。',
    )


