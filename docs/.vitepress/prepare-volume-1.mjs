export function escapeHtml(value) {
  return value.replace(/[&<>"']/g, (character) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[character])
}

function readSvgSize(file) {
  const head = readFileSync(file, 'utf8').slice(0, 4000)
  const viewBox = head.match(/viewBox="\s*[-\d.]+\s+[-\d.]+\s+([\d.]+)\s+([\d.]+)\s*"/)
  if (viewBox) return { width: Number(viewBox[1]), height: Number(viewBox[2]) }
  const width = head.match(/\swidth="([\d.]+)(?:px)?"/)
  const height = head.match(/\sheight="([\d.]+)(?:px)?"/)
  return width && height ? { width: Number(width[1]), height: Number(height[1]) } : null
}

export function imageSize(file) {
  if (!existsSync(file)) return null
  if (file.endsWith('.svg')) return readSvgSize(file)
  const buffer = readFileSync(file)
  if (buffer.subarray(0, 8).toString('hex') === '89504e470d0a1a0a') {
    return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) }
  }
  if (buffer[0] === 0xff && buffer[1] === 0xd8) {
    for (let i = 2; i + 9 < buffer.length;) {
      if (buffer[i] !== 0xff) { i += 1; continue }
      const code = buffer[i + 1]
      if (code >= 0xc0 && code <= 0xcf && code !== 0xc4 && code !== 0xc8 && code !== 0xcc) {
        return { width: buffer.readUInt16BE(i + 7), height: buffer.readUInt16BE(i + 5) }
      }
      i += 2 + buffer.readUInt16BE(i + 2)
    }
  }
  if (buffer.toString('ascii', 0, 4) === 'RIFF' && buffer.toString('ascii', 8, 12) === 'WEBP') {
    const fourcc = buffer.toString('ascii', 12, 16)
    if (fourcc === 'VP8X') {
      return { width: buffer.readUIntLE(24, 3) + 1, height: buffer.readUIntLE(27, 3) + 1 }
    }
    if (fourcc === 'VP8L') {
      const bits = buffer.readUInt32LE(21)
      return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 }
    }
    if (fourcc === 'VP8 ') {
      return { width: buffer.readUInt16LE(26) & 0x3fff, height: buffer.readUInt16LE(28) & 0x3fff }
    }
  }
  return null
}

/**
 * 原书少数 <img> 的 alt 里直接写了英文引号和 `<`（如 “卡"5V…"”、“系数<1”）。
 * MkDocs 把它们当原始 HTML 透传，浏览器只把 alt 截断；Vue 模板编译器则直接报错。
 * alt 是这些标签里唯一的自由文本属性，定位它的收尾引号后把内部 `"` `<` 转义。
 */
export function repairImageAttributes(attributes) {
  const alt = attributes.match(/\balt\s*=\s*"/)
  if (!alt) return attributes
  const valueStart = alt.index + alt[0].length
  let end = -1
  for (let index = valueStart; index < attributes.length; index += 1) {
    if (attributes[index] !== '"') continue
    // 首个「后面跟着空格+属性名=」的引号就是 alt 的收尾引号；继续往后扫会把
    // width/height 等后续属性整段吞进 alt 值再转义（2026-11-12 路线图页实测）。
    if (/^\s*(?:[A-Za-z_:][-A-Za-z0-9_:.]*\s*=|$)/.test(attributes.slice(index + 1))) {
      end = index
      break
    }
  }
  if (end < 0) return attributes
  const value = attributes.slice(valueStart, end)
  if (!/[<"]/.test(value)) return attributes
  const escaped = value.replace(/"/g, '&quot;').replace(/</g, '&lt;')
  return attributes.slice(0, valueStart) + escaped + attributes.slice(end)
}

function setAttribute(attributes, name, value) {
  const pattern = new RegExp(`\\s${name}="[^"]*"`)
  if (pattern.test(attributes)) return attributes.replace(pattern, ` ${name}="${value}"`)
  return `${attributes} ${name}="${value}"`
}

